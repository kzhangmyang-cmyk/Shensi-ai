import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {parseHTML}=createRequire(new URL('../../frontend/package.json',import.meta.url))('linkedom');
import {mountCfoConversation} from '../../frontend/src/growth/agents/cfo-conversation';
import {createGrowthHttpClient} from '../../frontend/src/growth/http';
import {AgentOperatingMemoryService} from '../src/agent-operating-memory';
import {MemoryDecisionMemoryRepository} from '../src/decision-memory-repository';
import {DecisionSimulationService,MemoryDecisionSimulationRepository} from '../src/decision-simulation-service';
import {operatingExample} from '../../frontend/src/decision-simulation/samples';
const tick=()=>new Promise(r=>setTimeout(r,0));
test('center uses the same saved operating memory and report-review controls without automatic application',async()=>{
 const scope={actorId:'synthetic',workspaceId:'isolated'};
 const reports=new DecisionSimulationService(new MemoryDecisionSimulationRepository());
 const report=await reports.create(scope,{...operatingExample('normal'),title:'隔离合成 · 共享复盘'});
 const memory=new AgentOperatingMemoryService(new MemoryDecisionMemoryRepository(),reports);
 await memory.saveProfile(scope,{expectedRevision:0,enabled:true,preferences:{priority:'profit',pilotFirst:true,reviewCadence:'weekly',learningEnabled:false,confirmedFrom:'self_report'}});
 const questions:{path:string;body:Record<string,unknown>}[]=[];
 const http=createGrowthHttpClient({fetchImpl:async(path,options)=>{
  let body:unknown;const input=options?.body?JSON.parse(String(options.body)):undefined;
  if(path==='/api/v1/agent-memory/operating')body=await memory.get(scope);
  else if(path==='/api/v1/decision-simulations')body=await reports.list(scope);
  else if(path===`/api/v1/decision-simulations/${report.runId}`)body=report;
  else if(path==='/api/v1/agent-memory/operating/reviews')body=await memory.saveReview(scope,input);
  else if(path.endsWith('/cfo-sessions'))body=null;
  else if(path.endsWith('/cfo-workflows/latest'))body=null;
  else if(path.endsWith('/cfo-conversation')||path.endsWith('/operating-memory-question')){
   questions.push({path,body:input});const answer={answer:'合成只读建议',provider:'fixture',model:'fixture',material:null,answeredAt:new Date().toISOString()};
   body=path.endsWith('/operating-memory-question')?{answer}:answer;
  }else throw new Error(`Unexpected ${path}`);
  return new Response(JSON.stringify(body),{status:200,headers:{'content-type':'application/json'}});
 }});
 const {document,window}=parseHTML('<html><body><main></main></body></html>');const host=document.querySelector<HTMLElement>('main')!;
 const view=mountCfoConversation({host,http,scope:()=> 'isolated:synthetic'});
 host.querySelector<HTMLButtonElement>('[data-cfo-role-choice=finance]')!.click();
 host.querySelector<HTMLElement>('[data-agent-operating-workbench]>summary')!.click();await tick();
 const send=async()=>{host.querySelector<HTMLTextAreaElement>('textarea')!.value='合成经营建议';host.querySelector('[data-cfo-question-form]')!.dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await tick();};
 await send();assert.equal(questions.length,1,host.querySelector('[data-cfo-status]')!.textContent!);assert.ok(questions[0].path.endsWith('/cfo-conversation'));
 host.querySelector<HTMLButtonElement>('[data-memory-use]')!.click();await send();
 assert.deepEqual(questions[1].body.selection,{domain:'operating',revision:1});
 host.querySelector<HTMLButtonElement>('[data-operating-reports]')!.click();await tick();
 host.querySelector<HTMLButtonElement>('[data-operating-report]')!.click();await tick();await tick();
 const card=host.querySelector<HTMLElement>('[data-review-id=procurement]')!;assert.ok(card);
 for(const [key,value] of Object.entries({metric:'单位成本',unit:'元/件',baseline:'100',target:'80',dueDate:'2026-10-01',planSource:'隔离合成报价'}))card.querySelector<HTMLInputElement>(`[data-review-field=${key}]`)!.value=value;
 card.querySelector<HTMLButtonElement>('[data-save-plan]')!.click();await tick();
 assert.equal((await memory.get(scope)).reviews[0].plan.target,80);
 assert.deepEqual(await reports.get(scope,report.runId),report);
 host.querySelector<HTMLButtonElement>('[data-cfo-role-choice=tax]')!.click();await send();assert.ok(questions[2].path.endsWith('/cfo-conversation'));
 view.dispose();
});
